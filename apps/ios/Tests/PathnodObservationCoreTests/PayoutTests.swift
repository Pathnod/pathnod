import CryptoKit
import XCTest
@testable import PathnodObservationCore

final class PayoutTests: XCTestCase {
    func testExpiredBlockhashAllowsReplacementWhileAuthorizationIsStillValid() throws {
        // Authorization still has 83 seconds remaining: transaction height, not
        // authorization time, determines whether the old wire can be replaced.
        let now: UInt64 = 2_000_000_000, authorizationExpiry = now + 83
        XCTAssertGreaterThan(authorizationExpiry, now)
        XCTAssertEqual(try WithdrawalRecovery.action(status:.absent,finalizedHeight:151,
            lastValidBlockHeight:150,savedNonce:0,finalizedNonce:0),.replace)
        XCTAssertEqual(try WithdrawalRecovery.action(status:.absent,finalizedHeight:150,
            lastValidBlockHeight:150,savedNonce:0,finalizedNonce:0),.retry)
    }
    func testLostResponseAndAmbiguousRecoveryCannotDuplicateWithdrawal() throws {
        XCTAssertEqual(try WithdrawalRecovery.action(status:.absent,finalizedHeight:151,
            lastValidBlockHeight:150,savedNonce:0,finalizedNonce:1),.completed)
        for transaction in [WithdrawalTransactionStatus.pending, .finalized] {
            XCTAssertEqual(try WithdrawalRecovery.action(status:transaction,finalizedHeight:151,
                lastValidBlockHeight:150,savedNonce:0,finalizedNonce:0),.wait)
        }
        XCTAssertEqual(try WithdrawalRecovery.action(status:.absent,finalizedHeight:151,
            lastValidBlockHeight:nil,savedNonce:0,finalizedNonce:0),.wait)
        XCTAssertThrowsError(try WithdrawalRecovery.action(status:.absent,finalizedHeight:151,
            lastValidBlockHeight:150,savedNonce:1,finalizedNonce:0))
    }
    func testFailedTransactionStillRequiresFinalizedExpiryBeforeReplacement() throws {
        XCTAssertEqual(try WithdrawalRecovery.action(status:.failed,finalizedHeight:150,
            lastValidBlockHeight:150,savedNonce:0,finalizedNonce:0),.wait)
        XCTAssertEqual(try WithdrawalRecovery.action(status:.failed,finalizedHeight:151,
            lastValidBlockHeight:150,savedNonce:0,finalizedNonce:0),.replace)
    }
