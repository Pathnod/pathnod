    func testBase58AndIntegerAmounts() throws {
        for key in [Data(repeating: 0, count: 32), Data(repeating: 255, count: 32), Curve25519.Signing.PrivateKey().publicKey.rawRepresentation] {
            XCTAssertEqual(try SolanaBase58.decode32(SolanaBase58.encode(key)), key)
        }
        XCTAssertEqual(try PayoutBalance.baseUnits("0.040000"), 40_000)
        XCTAssertEqual(try PayoutBalance.baseUnits("18446744073709.551615"), UInt64.max)
        for amount in ["1.2", "-1.000000", "18446744073709.551616", "0.nan000"] {
            XCTAssertThrowsError(try PayoutBalance.baseUnits(amount))
        }
        XCTAssertThrowsError(try SolanaBase58.decode32("0"))
        XCTAssertThrowsError(try SolanaBase58.decode32(String(repeating: "1", count: 33)))
    }
